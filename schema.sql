CREATE SCHEMA IF NOT EXISTS nikita_zozulenko;
SET search_path TO nikita_zozulenko;
CREATE TABLE IF NOT EXISTS users (
 id bigint PRIMARY KEY, username text NOT NULL, display_name text NOT NULL,
 is_staff boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS categories (
 id bigint PRIMARY KEY, name text NOT NULL, norm_minutes integer NOT NULL CHECK(norm_minutes>0)
);
CREATE TABLE IF NOT EXISTS tickets (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), category_id bigint NOT NULL REFERENCES categories(id),
 title text NOT NULL, body text NOT NULL,
 status text NOT NULL CHECK(status IN ('new','in_progress','closed')),
 created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS comments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id bigint NOT NULL REFERENCES tickets(id), user_id bigint NOT NULL REFERENCES users(id),
 body text NOT NULL, created_at timestamptz NOT NULL
);
